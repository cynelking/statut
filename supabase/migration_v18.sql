-- Admin-published announcements shown in the feed and delivered through Web Push.
create table public.announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 120),
  body text not null check (char_length(btrim(body)) between 1 and 2000),
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create index announcements_created_at_idx on public.announcements (created_at desc, id desc);

alter table public.announcements enable row level security;

create policy announcements_read_authenticated
  on public.announcements for select to authenticated
  using (true);

create policy announcements_insert_admin
  on public.announcements for insert to authenticated
  with check (public.is_admin() and created_by = auth.uid());

grant select on public.announcements to authenticated;
grant insert on public.announcements to authenticated;
grant usage, select on sequence public.announcements_id_seq to authenticated;

notify pgrst, 'reload schema';
